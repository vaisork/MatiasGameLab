import assert from 'node:assert/strict';
import {NarrativeJournal} from './ui-data.js';
const world=text=>({kind:'world',text}),action=text=>({kind:'action',text});
const snapshot=(room='pozo',scene=[world('El pozo tiene dos cuerdas.')],narrative=scene,id=1)=>({character:{id},room:{id:room,name:room},scene,narrative});
const journal=new NarrativeJournal();
journal.consume(snapshot());assert.equal(journal.entries.length,2); // Title and scene once, not twice.
for(let i=0;i<10;i++)journal.consume(snapshot());assert.equal(journal.entries.length,2);
journal.consume(snapshot('pozo',undefined,[action('Pruebas el cubo.')]),true);
assert.equal(journal.entries.length,3);assert.equal(journal.entries.at(-1).text,'Pruebas el cubo.');
journal.consume(snapshot('pozo',undefined,[action('Pruebas el cubo.')]));assert.equal(journal.entries.length,3);
journal.consume(snapshot('pozo',[world('La lluvia oscurece la piedra.')],[action('Pruebas el cubo.')]));
assert.equal(journal.entries.length,4);assert.equal(journal.entries.at(-1).text,'La lluvia oscurece la piedra.');
journal.consume(snapshot('plaza',[world('La plaza se abre al camino.')]),true);
assert.equal(journal.entries.filter(e=>e.text==='La plaza se abre al camino.').length,1);
journal.consume(snapshot('pozo'),true);assert.equal(journal.entries.at(-1).text,'El pozo tiene dos cuerdas.');
const before=journal.entries.length;
journal.consume(snapshot('pozo',undefined,[world('El pozo tiene dos cuerdas.')]),true);
assert.equal(journal.entries.length,before); // Observing never duplicates the current scene.
const existing=journal.entries;
journal.consume(snapshot('hogar',[world('Otro personaje, otro hogar.')],undefined,2));
assert.equal(journal.entries,existing);assert.equal(journal.entries.length,2);assert.equal(journal.entries[0].key,'2:1');
for(let i=0;i<150;i++)journal.consume(snapshot('hogar',[world('Otro personaje, otro hogar.')],[action('Decisión '+i)],2),true);
assert.equal(journal.entries.length,100);assert.equal(new Set(journal.entries.map(e=>e.key)).size,100);
journal.reset();assert.equal(journal.entries.length,0);

