travel.consume({...snapshot('puente'),room:{id:'puente',name:'Puente',region:'lethra'}},true);
assert.equal(travel.entries.filter(e=>e.text==='Llegas a Puente.').length,1);
assert.equal(travel.entries.filter(e=>e.text==='Entras en Aguas de Lethra.').length,1);
const length=travel.entries.length;
travel.consume({...snapshot('puente'),room:{id:'puente',name:'Puente',region:'lethra'}});
assert.equal(travel.entries.length,length);
